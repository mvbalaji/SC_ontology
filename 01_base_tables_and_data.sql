-- DIM_LANE (500 rows)
CREATE OR REPLACE TABLE SCS.INVENTORY.DIM_LANE (
    LANE_ID          INT         NOT NULL PRIMARY KEY,
    ORIGIN_PORT_ID   INT         NOT NULL,
    DEST_PORT_ID     INT         NOT NULL,
    TRANSPORT_MODE   VARCHAR(20) NOT NULL,
    TRANSIT_DAYS_AVG INT         NOT NULL,
    IS_PROBLEM_LANE  BOOLEAN     DEFAULT FALSE
) COMMENT = 'Shipping lanes between ports';

INSERT INTO SCS.INVENTORY.DIM_LANE
WITH LANE_GEN AS (
    SELECT
        ROW_NUMBER() OVER (ORDER BY O.PORT_ID, D.PORT_ID) AS RN,
        O.PORT_ID AS ORIGIN_PORT_ID,
        D.PORT_ID AS DEST_PORT_ID,
        CASE
            WHEN O.PORT_TYPE = 'AIR' OR D.PORT_TYPE = 'AIR' THEN 'AIR'
            ELSE 'OCEAN'
        END AS TRANSPORT_MODE,
        CASE
            WHEN O.PORT_TYPE = 'AIR' OR D.PORT_TYPE = 'AIR' THEN 2 + MOD(ABS(HASH(O.PORT_ID, D.PORT_ID)), 5)
            ELSE 14 + MOD(ABS(HASH(O.PORT_ID, D.PORT_ID)), 30)
        END AS TRANSIT_DAYS_AVG
    FROM SCS.INVENTORY.DIM_PORT O
    CROSS JOIN SCS.INVENTORY.DIM_PORT D
    WHERE O.PORT_ID != D.PORT_ID
      AND MOD(ABS(HASH(O.PORT_ID, D.PORT_ID, 20260917)), 100) < 35
)
SELECT
    RN AS LANE_ID,
    ORIGIN_PORT_ID,
    DEST_PORT_ID,
    TRANSPORT_MODE,
    TRANSIT_DAYS_AVG,
    -- Mark Shenzhen-to-Guadalajara ocean lane as problem
    (ORIGIN_PORT_ID IN (SELECT PORT_ID FROM SCS.INVENTORY.DIM_PORT WHERE PORT_CODE = 'CNSZX')
     AND DEST_PORT_ID IN (SELECT PORT_ID FROM SCS.INVENTORY.DIM_PORT WHERE PORT_CODE = 'MXGDL'))
    AS IS_PROBLEM_LANE
FROM LANE_GEN
WHERE RN <= 500;

