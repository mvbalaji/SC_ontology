CREATE OR REPLACE TABLE SCS.INVENTORY.FACT_INVENTORY_SNAPSHOT (
    SNAPSHOT_ID     INT           NOT NULL PRIMARY KEY,
    SNAPSHOT_DATE   DATE          NOT NULL,
    PART_ID         INT           NOT NULL,
    WAREHOUSE_ID    INT           NOT NULL,
    ON_HAND_QTY     DECIMAL(12,2) NOT NULL,
    UNIT_COST_USD   DECIMAL(10,2) NOT NULL,
    ON_HAND_VALUE   DECIMAL(14,2) NOT NULL COMMENT 'on_hand_qty * unit_cost_usd',
    DAILY_USAGE_QTY DECIMAL(10,2) COMMENT 'Average daily consumption',
    DOI             DECIMAL(10,1) COMMENT 'Days of inventory = on_hand / daily_usage'
) COMMENT = 'Inventory snapshots — ~1.2M rows (part x warehouse x month-end)';

INSERT INTO SCS.INVENTORY.FACT_INVENTORY_SNAPSHOT
SELECT
    SEQ8() + 1 AS SNAPSHOT_ID,
    DATEADD(MONTH, MOD(SEQ8(), 48), '2023-01-31')::DATE AS SNAPSHOT_DATE,
    MOD(ABS(HASH(SEQ8(), 20260917)), 1000) + 1 AS PART_ID,
    MOD(ABS(HASH(SEQ8(), 20260918)), 25) + 1 AS WAREHOUSE_ID,
    GREATEST(0, (100 + MOD(ABS(HASH(SEQ8(), 20260919)), 9900))::DECIMAL(12,2)) AS ON_HAND_QTY,
    ROUND(0.50 + MOD(ABS(HASH(SEQ8(), 20260920)), 50000) / 100.0, 2) AS UNIT_COST_USD,
    ROUND(GREATEST(0, (100 + MOD(ABS(HASH(SEQ8(), 20260919)), 9900)))
        * (0.50 + MOD(ABS(HASH(SEQ8(), 20260920)), 50000) / 100.0), 2) AS ON_HAND_VALUE,
    GREATEST(0.1, ROUND(MOD(ABS(HASH(SEQ8(), 20260921)), 500) / 10.0, 2)) AS DAILY_USAGE_QTY,
    ROUND(
        GREATEST(0, (100 + MOD(ABS(HASH(SEQ8(), 20260919)), 9900)))
        / NULLIF(GREATEST(0.1, MOD(ABS(HASH(SEQ8(), 20260921)), 500) / 10.0), 0),
    1) AS DOI
FROM TABLE(GENERATOR(ROWCOUNT => 1200000));

