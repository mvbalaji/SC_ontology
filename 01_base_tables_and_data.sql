WITH SUPPLIER_PREFIXES AS (
    SELECT R.VALUE::VARCHAR AS PREFIX, R.INDEX AS IDX FROM TABLE(FLATTEN(INPUT => ARRAY_CONSTRUCT(
        'NEXORA','BLUEFORGE','PENTAWAVE','VERTEX','SOLARIS','QUANTUM','APEX','ORION',
