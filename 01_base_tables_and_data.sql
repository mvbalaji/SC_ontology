INSERT INTO SCS.INVENTORY.QUALITY_INSPECTION
SELECT
    SEQ8() + 1 AS INSPECTION_ID,
    MOD(ABS(HASH(SEQ8(), 20260917)), 90000) + 1 AS RECEIPT_ID,
    MOD(ABS(HASH(SEQ8(), 20260918)), 30000) + 1 AS PART_ID,
