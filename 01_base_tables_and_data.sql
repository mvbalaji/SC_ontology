-- DIM_DATE: 2022-01-01 through 2026-12-31 (1,826 rows)
CREATE OR REPLACE TABLE SCS.INVENTORY.DIM_DATE (
    DATE_KEY        DATE        NOT NULL PRIMARY KEY,
    YEAR            INT         NOT NULL,
    QUARTER         INT         NOT NULL,
    MONTH           INT         NOT NULL,
    MONTH_NAME      VARCHAR(10) NOT NULL,
    WEEK_OF_YEAR    INT         NOT NULL,
    DAY_OF_WEEK     INT         NOT NULL,
    DAY_NAME        VARCHAR(10) NOT NULL,
    IS_WEEKEND      BOOLEAN     NOT NULL,
    FISCAL_YEAR     INT         NOT NULL,
    FISCAL_QUARTER  INT         NOT NULL
) COMMENT = 'Calendar dimension from 2022-01-01 to 2026-12-31';

INSERT INTO SCS.INVENTORY.DIM_DATE
SELECT
    DT,
    YEAR(DT),
    QUARTER(DT),
    MONTH(DT),
    MONTHNAME(DT),
    WEEKOFYEAR(DT),
    DAYOFWEEK(DT),
    DAYNAME(DT),
    DAYOFWEEK(DT) IN (0, 6),
    CASE WHEN MONTH(DT) >= 7 THEN YEAR(DT) + 1 ELSE YEAR(DT) END,
    CASE WHEN MONTH(DT) >= 7 THEN QUARTER(DT) - 2 ELSE QUARTER(DT) + 2 END
FROM (
    SELECT DATEADD(DAY, SEQ4(), '2022-01-01'::DATE) AS DT
    FROM TABLE(GENERATOR(ROWCOUNT => 1827))
)
WHERE DT <= '2026-12-31';

