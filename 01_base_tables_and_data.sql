        'CRYO','FERRO','AERO','HYDRO','ELECTRO','MAGNETO','PHOTON'
    ))) R
),
SUPPLIER_SUFFIXES AS (
    SELECT R.VALUE::VARCHAR AS SUFFIX, R.INDEX AS IDX FROM TABLE(FLATTEN(INPUT => ARRAY_CONSTRUCT(
        'SEMICONDUCTORS','COMPONENTS','MATERIALS','ELECTRONICS','TECHNOLOGIES',
        'PRECISION','SYSTEMS','SOLUTIONS','INDUSTRIES','MANUFACTURING'
    ))) R
),
SUPPLIER_BASE AS (
    SELECT
        ROW_NUMBER() OVER (ORDER BY P.IDX, S.IDX) AS RN,
        P.PREFIX || ' ' || S.SUFFIX AS SNAME,
        P.PREFIX,
        S.SUFFIX
    FROM SUPPLIER_PREFIXES P
    CROSS JOIN SUPPLIER_SUFFIXES S
)
SELECT
    RN AS SUPPLIER_ID,
    SNAME AS SUPPLIER_NAME,
    'SUP-' || LPAD(RN::VARCHAR, 5, '0') AS SUPPLIER_CODE,
    MOD(ABS(HASH(RN, 20260917)), 24) + 1 AS COUNTRY_ID,
    MOD(ABS(HASH(RN, 20260918)), 12) + 1 AS COMMODITY_ID,
    ROUND(0.60 + (MOD(ABS(HASH(RN, 20260919)), 40) / 100.0), 2) AS RELIABILITY_RATING,
    SNAME IN ('NEXORA SEMICONDUCTORS','BLUEFORGE COMPONENTS','PENTAWAVE MATERIALS') AS IS_PROBLEM,
    TRUE AS ACTIVE,
    TRUE AS IS_SYNTHETIC
FROM SUPPLIER_BASE
WHERE RN <= 500;

